const pos = CODES.map((r) => src.indexOf('data-cbsid="' + r[0] + '"'));
check(pos.every((p, i) => p > 0 && (i === 0 || p > pos[i - 1])), 'the ' + CODES.length + ' codes appear in file order (no two codes of one marker swapped)');
