/** the open tag around a code: from the '<' before it to the first '>' after it (the strings hold no '>' inside a tag here) */
function tagAround(code) {
  const at = src.indexOf('data-cbsid="' + code + '"');
  if (at < 0) return null;
  const open = src.lastIndexOf('<', at), end = src.indexOf('>', at);
  return { name: (src.slice(open + 1, at).match(/^[a-z]+/) || [''])[0], body: src.slice(open, end + 1) };
}
