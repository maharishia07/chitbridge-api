  check(at > 0 && body.indexOf('<' + tag) === 0 && body.indexOf('data-cbsid="' + code + '"') > 0 && body.indexOf(marker) >= 0, code + ' + ' + mount + ' sit in the same <' + tag + '> (' + marker + ')');
