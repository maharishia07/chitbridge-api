function cmdbPaint() {
  var body = document.getElementById('cbcmdbbody'),
    head = document.getElementById('cbcmdbhead');
  if (!body || !head) return;
  var all = cmdbRows();
  var groups = [];
  all.forEach(function (item) {
    if (groups.indexOf(item.group) < 0) groups.push(item.group);
  });

  var q = String(CBCMDB.q || '').toLowerCase();
  var rows = all.filter(function (item) {
    if (CBCMDB.group && item.group !== CBCMDB.group) return false;
    if (!q) return true;
    return (item.code + ' ' + item.path).toLowerCase().indexOf(q) >= 0;
  });

  var ico =
    'border:1px solid var(--line,#e7e3d8);background:var(--card,#fff);cursor:pointer;border-radius:7px;' +
    'width:24px;height:24px;font-size:var(--fs-1);line-height:1;padding:0;color:var(--grey-2,#545A61)';
  head.innerHTML =
    '<div style="display:flex;align-items:center;gap:6px">' +
    '<b style="font-size:var(--fs-3);white-space:nowrap">\uD83D\uDDC2\uFE0F Configuration register</b>' +
    '<span style="flex:1 1 auto"></span>' +
    '<button data-cbsid="SCR011-B02" title="Minimise" onclick="cmdbMinimise()" style="' +
    ico +
    '">\u2013</button>' +
    '<button data-cbsid="SCR011-B03" title="Close" onclick="cmdbSet(false)" style="' +
    ico +
    '">\u2715</button>' +
    '</div>' +
    /**
     * ⭐ ONE SWITCH, FOUR KINDS OF CONFIGURATION ITEM. ⚠️ Screens first because they are what a person points at
     * — an incident is reported as "the catalogue setup screen", never as "cap-catsetup.js".
     */
    '<div style="display:flex;gap:4px;flex-wrap:wrap;margin-top:7px">' +
    cmdbKindsHTML() +
    '</div>' +
    '<div style="display:flex;gap:5px;flex-wrap:wrap;margin-top:6px;align-items:center">' +
    (CBCMDB.kind === 'SCREEN'
      ? '<select data-cbsid="SCR011-S01" onchange="cmdbFilter(\'group\',this.value)" style="font-size:var(--fs-2);padding:3px 5px">' +
        '<option value="">Every menu \u00b7 ' +
        all.length +
        '</option>' +
        groups
          .map(function (item) {
            var n = all.filter(function (r) {
              return r.group === item;
            }).length;
            return '<option value="' + esc(item) + '"' + (CBCMDB.group === item ? ' selected' : '') + '>' + esc(item) + ' \u00b7 ' + n + '</option>';
          })
          .join('') +
        '</select>'
      : '') +
    '<input data-cbsid="SCR011-I01" value="' +
    esc(CBCMDB.q) +
    '" oninput="cmdbFilter(\'q\',this.value)" placeholder="code or name"' +
    ' style="flex:1 1 140px;font-size:var(--fs-2);padding:3px 6px;border:1px solid var(--line,#e7e3d8);' +
    'border-radius:7px;background:var(--card,#fff);color:var(--ink)">' +
    '</div>';

  if (!all.length) {
    /* ⚠️ says WHICH empty it is: a missing generated file is a build problem, not an empty register */
    body.innerHTML =
      '<div style="padding:10px 0;font-size:var(--fs-2);color:var(--note)">' +
      'The register did not load. <code>/app/screens.js</code> is generated by <code>node screens.cjs</code> ' +
      'and committed \u2014 if it is missing, the build is short of a file rather than the register being empty.</div>';
    return;
  }

  var q2 = 'font-size:var(--fs-1);color:var(--note)';
  if (CBCMDB.kind === 'PANEL') {
    body.innerHTML = cmdbPanelHTML(q2);
    return;
  }
  if (CBCMDB.kind === 'GONE') {
    body.innerHTML = cmdbGoneHTML(q2);
    return;
  }
  if (CBCMDB.kind === 'POPUP') {
    body.innerHTML = cmdbPopupHTML(q2);
    return;
  }
  if (CBCMDB.kind === 'CONTROL') {
    body.innerHTML = cmdbControlHTML(q2);
    return;
  }
  if (CBCMDB.kind !== 'SCREEN') {
    body.innerHTML = cmdbSoftwareHTML(q2);
    return;
  }
  var h =
    '<div style="padding:7px 0 8px;font-size:var(--fs-1);color:var(--grey-2,#545A61);line-height:1.5">' +
    '<b>' +
    rows.length +
    '</b> configuration item(s). Every screen carries a code that is <b>assigned once and ' +
    'never reused</b>, so a note quoting it means the same screen in a year.' +
    /* ⚠️⚠️ THE SENTENCE THAT KEEPS THIS HONEST. A register that looks complete is worse than a short one. */
    '<br>\u26a0\ufe0f Screens only, so far. Controls, reports, capabilities, engines and environments are ' +
    'configuration items too and have no identifier yet.' +
    '</div>';

  h +=
    '<table style="width:100%;border-collapse:collapse;font-size:var(--fs-2)">' +
    '<tr style="text-align:start;color:var(--grey-2,#545A61);font-size:var(--fs-1)">' +
    '<th style="text-align:start;padding:3px 6px 3px 0">Code</th>' +
    '<th style="text-align:start;padding:3px 6px">Menu</th>' +
    '<th style="text-align:start;padding:3px 6px">Screen</th>' +
    '<th style="text-align:end;padding:3px 6px" title="Cases on the board for this screen. ' +
    'Not coverage of its controls.">Cases</th>' +
    '<th style="text-align:start;padding:3px 0 3px 6px">Drawn by</th></tr>';
  rows.forEach(function (item) {
    h +=
      '<tr style="border-top:1px solid var(--line,#efece4)">' +
      '<td style="padding:4px 6px 4px 0"><code style="font-family:\'Space Mono\',ui-monospace,monospace;' +
      'user-select:all;color:var(--ink)">' +
      esc(item.code) +
      '</code></td>' +
      '<td style="padding:4px 6px;' +
      q2 +
      '">' +
      esc(item.group) +
      '</td>' +
      '<td style="padding:4px 6px">' +
      esc(item.screen) +
      '</td>' +
      '<td style="padding:4px 6px;text-align:end;font-variant-numeric:tabular-nums;' +
      (item.cases <= 1 ? q2 : '') +
      '">' +
      item.cases +
      '</td>' +
      /* ⭐⭐ THE MIDDLE LINK OF THE CHAIN: spec → case → SCREEN → SOFTWARE → result. It existed nowhere until
         today; the sweep computed it to emit controls once per screen and then threw it away. */
      '<td style="padding:4px 0 4px 6px;' +
      q2 +
      '">' +
      esc(String(cmdbDrawnBy(item.code) || '').replace('chitbridge-web/public/app/', '')) +
      '</td>' +
      '</tr>';
  });
  h += '</table>';
  body.innerHTML = h;
}
