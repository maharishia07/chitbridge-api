#!/usr/bin/env node
'use strict';
/*
 * OWNS      docs/contracts/paged-read-routes.json: the GET list routes of the API register with their paged-read facts, as the one file the WEB scan reads (web e2e/fixtures/paged-read-routes.json is a byte copy, as web-api.contract.json is).
 * CALLED BY by hand after `node tools/api-register.cjs` · tests/paged-read.test.cjs (the file equals what the register says) · the web's tools/paged-reads-web.cjs
 * FLOW      docs/api-register.json (reported_facts.paged_read, kind 'list') ──▶ { key, path, mode, default, max, unasked } per list route ──▶ docs/contracts/paged-read-routes.json
 * CARD      28-platform-and-operations/api-standard
 *   node tools/paged-reads-routes.cjs            write the file
 *   node tools/paged-reads-routes.cjs --check    exit 1 when it differs from the register
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'docs', 'contracts', 'paged-read-routes.json');

/** the list routes of a register, in the register's order */
function routesOf(register) {
  return register.routes
    .filter((row) => row.reported_facts && row.reported_facts.paged_read && row.reported_facts.paged_read.kind === 'list')
    .map((row) => { const f = row.reported_facts.paged_read; return { key: row.key, path: row.path, mode: f.mode, default: f.default, max: f.max, unasked: f.unasked }; });
}
const textOf = (register) => JSON.stringify({ version: 1, note: 'generated by tools/paged-reads-routes.cjs from docs/api-register.json; unasked: bounded = nothing asked still answers one default page, everything = every row, unknown = only the schema maximum is visible', routes: routesOf(register) }, null, 1) + '\n';

if (require.main === module) {
  const text = textOf(JSON.parse(fs.readFileSync(path.join(ROOT, 'docs', 'api-register.json'), 'utf8')));
  if (process.argv.includes('--check')) {
    const same = fs.existsSync(OUT) && fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') === text;
    console.log(same ? 'paged-read-routes.json ok' : 'docs/contracts/paged-read-routes.json differs from the register: run node tools/paged-reads-routes.cjs');
    process.exit(same ? 0 : 1);
  }
  fs.writeFileSync(OUT, text);
  console.log('wrote docs/contracts/paged-read-routes.json: ' + routesOf(JSON.parse(fs.readFileSync(path.join(ROOT, 'docs', 'api-register.json'), 'utf8'))).length + ' list routes');
}
module.exports = { routesOf, textOf };
